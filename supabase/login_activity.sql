-- Login activity history for the LMS Admin panel.
begin;

create table if not exists public.login_activities (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  email text,
  full_name text,
  logged_at timestamptz not null default now()
);

create index if not exists login_activities_logged_at_idx
  on public.login_activities (logged_at desc);
create index if not exists login_activities_user_id_idx
  on public.login_activities (user_id);

alter table public.login_activities enable row level security;

drop policy if exists "users record own login activity" on public.login_activities;
create policy "users record own login activity"
on public.login_activities
for insert to authenticated
with check (user_id = auth.uid());

drop policy if exists "admins read login activity" on public.login_activities;
create policy "admins read login activity"
on public.login_activities
for select to authenticated
using (public.is_admin());

grant insert on public.login_activities to authenticated;
grant select on public.login_activities to authenticated;
grant usage, select on sequence public.login_activities_id_seq to authenticated;

commit;
